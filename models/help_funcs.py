class GlobalContextBlock(nn.Module):
    """
    GCNet Module
    """

    def __init__(self, in_channels, reduction=16):
        super(GlobalContextBlock, self).__init__()
        self.in_channels = in_channels
        self.inter_channels = in_channels // reduction

        self.conv_mask = nn.Conv2d(self.in_channels, 1, kernel_size=1)
        self.softmax = nn.Softmax(dim=2)

        self.channel_add_conv = nn.Sequential(
            nn.Conv2d(self.in_channels, self.inter_channels, kernel_size=1),
            nn.LayerNorm([self.inter_channels, 1, 1]),
            nn.ReLU(inplace=True),
            nn.Conv2d(self.inter_channels, self.in_channels, kernel_size=1)
        )

    def forward(self, x):
        b, c, h, w = x.size()

        # [b, c, h, w] -> [b, 1, h, w]
        mask = self.conv_mask(x)
        # [b, 1, h, w] -> [b, 1, h*w]
        mask = mask.view(b, 1, h * w)
        # [b, 1, h*w]
        mask = self.softmax(mask)
        # [b, 1, h*w] -> [b, 1, h, w]
        mask = mask.view(b, 1, h, w)

        # [b, c, h, w] * [b, 1, h, w] -> [b, c, h, w]
        context = x * mask
        # [b, c, h, w] -> [b, c, 1, 1]
        context = torch.mean(context, dim=(2, 3), keepdim=True)

        # [b, c, 1, 1]
        channel_add = self.channel_add_conv(context)

        return x + channel_add


class AttentionGate(nn.Module):
    """
    Attention Gate for G-BiFPN
    """

    def __init__(self, F_g, F_l, F_int):
        super(AttentionGate, self).__init__()
        self.W_g = nn.Sequential(
            nn.Conv2d(F_g, F_int, kernel_size=1, stride=1, padding=0, bias=True),
            nn.BatchNorm2d(F_int)
        )

        self.W_x = nn.Sequential(
            nn.Conv2d(F_l, F_int, kernel_size=1, stride=1, padding=0, bias=True),
            nn.BatchNorm2d(F_int)
        )

        self.psi = nn.Sequential(
            nn.Conv2d(F_int, 1, kernel_size=1, stride=1, padding=0, bias=True),
            nn.BatchNorm2d(1),
            nn.Sigmoid()
        )

        self.relu = nn.ReLU(inplace=True)

    def forward(self, g, x):
        # g: gating signal from deep layer
        # x: skip connection from shallow layer
        g1 = self.W_g(g)
        x1 = self.W_x(x)
        psi = self.relu(g1 + x1)
        psi = self.psi(psi)
        return x * psi


